# Tupla vacía
empty_tuple = ()
print(empty_tuple)

# Crear tupla numeros
tenerife_geoloc= (28.46824,-16.25462)
print(tenerife_geoloc)

# Crear tupla strings
three_wise_men = ("Melchor❘", "Gaspar", "Baltasar")
print(three_wise_men)

# Hemos creado un string realmente
one_item_tuple = ("Papá Noel")
print(one_item_tuple)
print(type(one_item_tuple)) # = class 'str'

# Para crear una tupla de un elemento se le pone una coma
one_item_tuplev2 = ("Papá Noel",)
print(one_item_tuplev2)
print(type(one_item_tuplev2)) # = class 'tuple'

# Tuplas sin parentesis
one_item_tuplev3= "PapáNoel",
three_wise_men = "Melchor❘", "Gaspar", "Baltasar"
tenerife_geoloc= 28.46824,-16.25462
print(type(one_item_tuplev3)) # = class 'tuple'